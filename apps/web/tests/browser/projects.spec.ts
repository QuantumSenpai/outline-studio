import { test, expect } from '@playwright/test';

test('create, autosave, snapshots, compare, restore and reopen a local project', async ({ page }) => {
  await page.goto('/projects');
  await page.getByRole('button', { name: 'Reject optional cookies', exact: true }).click();
  await page.getByRole('combobox', { name: 'Starting template' }).selectOption('research');
  await page.getByRole('button', { name: 'Create local project' }).click();
  await expect(page).toHaveURL(/project=/);
  const url = page.url();
  const composer = page.getByRole('textbox', { name: 'Your document request' });
  await composer.fill('A research draft about urban heat islands.');
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await page.getByLabel('Snapshot name').fill('First direction');
  await page.getByRole('button', { name: 'Save named snapshot' }).click();
  await expect(page.getByText('Snapshot saved locally.', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Conversation', exact: true }).click();
  await composer.fill('A revised research draft about forest restoration.');
  await page.getByRole('tab', { name: 'History', exact: true }).click();
  await page.getByRole('button', { name: /First direction/ }).click();
  await expect(page.getByText('Draft request', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Restore as new revision' }).click();
  await page.getByRole('button', { name: 'Confirm restore' }).click();
  await expect(page.getByText(/Restored as a new revision/)).toBeVisible();
  await page.getByRole('tab', { name: 'Conversation', exact: true }).click();
  await expect(composer).toHaveValue('A research draft about urban heat islands.');
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible();
  await page.reload();
  await expect(composer).toHaveValue('A research draft about urban heat islands.');
  await page.goto('/projects');
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Urban restoration study');
  await page.getByRole('button', { name: 'Save project name' }).click();
  await page.getByLabel('Search local projects').fill('Urban restoration');
  await expect(page.getByRole('heading', { name: 'Urban restoration study' })).toBeVisible();
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click();
  await expect(page.locator('.project-list > li')).toHaveCount(2);
  const copy = page.locator('.project-list > li').filter({ hasText: '(copy)' });
  await copy.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('button', { name: 'Delete this project', exact: true }).click();
  await expect(page.locator('.project-list > li')).toHaveCount(1);
  await page.goto(url);
  await expect(composer).toHaveValue('A research draft about urban heat islands.');
});
